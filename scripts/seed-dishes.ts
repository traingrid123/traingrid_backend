async function main() {
  try {
    console.log('🍽️ Seeding dishes database...');

    let seededCount = 0;
    for (const dish of dishesData) {
      try {
        const servingSizeGrams = 100; // Standard serving size

        await prisma.foodItem.upsert({
          where: { name: dish.name },
          update: {
            caloriesPer100g: dish.calories,
            proteinPer100g: dish.protein,
            carbsPer100g: dish.carbs,
            fatsPer100g: dish.fats,
            fiberPer100g: dish.fiber,
            servingSizeGrams,
            isCustom: false,
            createdById: null
          },
          create: {
            name: dish.name,
            brand: null,
            caloriesPer100g: dish.calories,
            proteinPer100g: dish.protein,
            carbsPer100g: dish.carbs,
            fatsPer100g: dish.fats,
            fiberPer100g: dish.fiber,
            servingSizeGrams,
            isCustom: false,
            createdById: null
          }
        });
        seededCount++;
      } catch (error) {
        console.error(`❌ Error seeding ${dish.name}:`, error);
      }
    }

    console.log(`✅ Seeded ${seededCount}/${dishesData.length} dishes`);
  } catch (error) {
    console.error('❌ Error seeding dishes:', error);
  } finally {
    await prisma.$disconnect();
  }
}

